export function createInitialAgents(): AgentEntity[] {
  return ROSTER_SPECS.map((spec, index) => {
    const wp = WAYPOINTS[spec.deskWaypointId];
    const startPos: [number, number, number] = wp ? [...wp.position] : [0, 0, 0];
    return {
      id: spec.id,
      numericIndex: index,
      name: spec.name,
      gender: spec.gender,
      role: spec.role,
      department: spec.department,
      departmentLabel: DEPARTMENT_META[spec.department].label,
      homeRoomId: spec.homeRoomId,
      homeRoomDoorId: spec.homeRoomDoorId,
      deskWaypointId: spec.deskWaypointId,
      appearance: {
        shirtColor: spec.shirtColor,
        pantsColor: spec.pantsColor,
        skinColor: spec.skinColor,
        hairColor: spec.hairColor,
        heightScale: spec.heightScale,
        buildScale: spec.buildScale,
        hasGlasses: spec.hasGlasses,
        hairStyle: spec.hairStyle,
        outfitStyle: spec.outfitStyle,
        jacketColor: spec.jacketColor,
        shoesColor: spec.shoesColor,
        eyeColor: spec.eyeColor,
        facialHair: spec.facialHair,
        accessory: spec.accessory,
      },
      position: startPos,
      rotationY: wp?.facingRotationY ?? 0,
      path: [],
      pathIndex: 0,
      pendingStateAfterWalk: null,
      state: index % 5 === 0 ? 'Idle' : 'Working',
      stateTimerSec: 8 + (index % 7) * 3,
      energy: 72 + ((index * 7) % 24),
      mood: 70 + ((index * 5) % 25),
      stress: 14 + ((index * 9) % 24),
      productivity: 74 + ((index * 6) % 22),
      skills: spec.skills,
      currentTask: spec.currentTask,
      taskProgress: 20 + ((index * 11) % 60),
      speechText: null,
      speechRemainingSec: 0,
    };
  });
}
